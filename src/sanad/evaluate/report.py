"""Evaluation report: time-block split, event-level metrics, latency -> reports/metrics.{json,md}.

All numbers in the report are computed here from the generated ground truth and the
pipeline outputs; nothing is typed by hand (golden rule 8).
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from sanad import io
from sanad.config import generated_dir, processed_dir, reports_dir, usable_bounds
from sanad.evaluate.matching import match_cases
from sanad.evaluate.metrics import block_metrics, event_table

BLOCKS = ("train", "val", "test")


def _load(cfg: dict) -> tuple[pd.DataFrame, pd.DataFrame]:
    g, p = generated_dir(cfg), processed_dir(cfg)
    if not io.exists(p / "cases.csv"):
        raise FileNotFoundError(f"{p}/cases.csv not found — run `python -m sanad.cli run` first")
    cases = io.read_csv(p / "cases.csv")
    for c in ("start_utc", "end_utc"):
        cases[c] = pd.to_datetime(cases[c], utc=True)
    events = io.read_events(g)
    events["block"] = events.params_json.map(lambda s: json.loads(s).get("block", ""))
    return match_cases(cases, events), events


def evaluate_run(cfg: dict, out_dir: Path | None = None) -> Path:
    out_dir = Path(out_dir) if out_dir else reports_dir(cfg)
    out_dir.mkdir(parents=True, exist_ok=True)
    cases, events = _load(cfg)
    bounds = usable_bounds(cfg)
    res: dict = {"run_id": cfg["run_id"], "config": cfg.get("_config_path", ""), "seed": cfg["seed"],
                 "split": {k: [str(a), str(b)] for k, (a, b) in bounds.items()},
                 "embargo_hours": cfg["split"]["embargo_hours"], "blocks": {}}
    for b in BLOCKS:
        days = (bounds[b][1] - bounds[b][0]).total_seconds() / 86400
        res["blocks"][b] = block_metrics(cases[cases.block == b], events[events.block == b], days)
    # false alarms in the normal-only block (no injected events there)
    nb = cases[cases.block == "normal"]
    nd = (bounds["normal"][1] - bounds["normal"][0]).total_seconds() / 86400
    res["normal_block"] = {"cases": int(len(nb)), "cases_per_day": round(len(nb) / nd, 3),
                           "note": "used to fit Stage A; in-sample"}
    counts = events.groupby(["subtype", "block"]).size().unstack(fill_value=0)
    res["event_counts"] = {lab: {b: int(counts.loc[lab].get(b, 0)) for b in ("normal", "train", "val", "test")}
                           for lab in counts.index}
    lat_p = processed_dir(cfg) / "latency.json"
    res["latency"] = io.read_json(lat_p) if lat_p.exists() else {}
    cal_p = processed_dir(cfg) / "confidence_calibration.json"
    if cal_p.exists():
        cal = io.read_json(cal_p)
        res["confidence_calibration"] = {k: cal.get(k) for k in ("method", "n", "accuracy", "ece_before", "ece_after")}
    io.write_json(res, out_dir / "metrics.json")
    et = event_table(cases[cases.block == "test"], events[events.block == "test"])
    (out_dir / "metrics.md").write_text(_markdown(res, et), encoding="utf-8")
    return out_dir


def _fmt(x, pct: bool = False) -> str:
    if x is None or x != x:
        return "–"
    return f"{100 * x:.1f}%" if pct else (f"{x:.3f}" if isinstance(x, float) else str(x))


def _markdown(res: dict, et_test: pd.DataFrame) -> str:
    t = res["blocks"]["test"]
    L = [
        "# SANAD-Gabès — evaluation report",
        "",
        f"*Fictional process plant in the Gabès industrial zone. All parameters are simulation assumptions. "
        f"No measurement originates from a real company.* Generated by `python -m sanad.cli evaluate` "
        f"for run `{res['run_id']}` (config `{res['config']}`, seed {res['seed']}). Every number below is computed by the code.",
        "",
        "## Protocol",
        "",
        "Time-block split (config-driven), embargo of "
        f"{res['embargo_hours']} h at the start of each later block (no events placed, no cases scored):",
        "",
        "| Block | From (UTC) | To (UTC) | Use |",
        "|---|---|---|---|",
    ]
    use = {"normal": "fit Stage A (normalisation, thresholds, Isolation Forest)",
           "train": "rule/threshold development (in-sample)", "val": "isotonic confidence calibration",
           "test": "held-out evaluation (headline)"}
    for k, (a, b) in res["split"].items():
        L.append(f"| {k} | {a[:16]} | {b[:16]} | {use[k]} |")
    L += [
        "",
        "Event-level scoring: an injected event is *detected* if a case overlaps it (event window + 60 min "
        "tolerance, compatible equipment). Its *predicted class* is the verdict of the first matched case "
        "that did not abstain; UNCERTAIN if all matched cases abstained; MISSED if none matched. "
        "Precision is case-level. Normal motor starts are not anomalies: a case on one counts as a false positive.",
        "",
        "## Headline (test block)",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Injected events | {t['n_events']} |",
        f"| Event detection rate | {_fmt(t['event_detection_rate'], True)} |",
        f"| Event classification accuracy (correct class, abstentions count as wrong) | {_fmt(t['event_accuracy'], True)} |",
        f"| Cases raised | {t['n_cases']} |",
        f"| Abstention rate (UNCERTAIN cases / cases) | {_fmt(t['abstention_rate'], True)} |",
        f"| False-positive cases (no injected event) | {t['false_positive_cases']} |",
        f"| False positives per day | {_fmt(t['false_positives_per_day'])} |",
        f"| … of which on normal motor starts | {t['false_positive_on_normal_starts']} |",
        "",
        "## Per class (test block)",
        "",
        "| Class | Events | Detected | Recall | Cases predicted | Precision | F1 | Abstained events | Median delay (min) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for cls, m in t["per_class"].items():
        L.append(f"| {cls} | {m['events']} | {m['detected']} | {_fmt(m['recall'], True)} | {m['cases_predicted']} | "
                 f"{_fmt(m['precision'], True)} | {_fmt(m['f1'], True)} | {m['abstained_events']} | {_fmt(m['delay_min_median'])} |")
    L += ["", "## Per injection label (test block)", "",
          "| Label | Events | Detected | Correct class | Uncertain | Median delay (min) |", "|---|---|---|---|---|---|"]
    for lab, m in t["per_label"].items():
        L.append(f"| {lab} | {m['events']} | {m['detected']} | {m['correct']} | {m['uncertain']} | {_fmt(m['delay_min_median'])} |")
    L += ["", "## Confusion matrix (test block, events: truth × predicted)", ""]
    cm = t["confusion_matrix"]
    if cm:
        cols = list(next(iter(cm.values())).keys())
        short = {c: c.replace("PHYSICAL_EQUIPMENT_FAULT", "PHYS").replace("BIAS_MISCALIBRATION", "BIAS")
                 .replace("CORRUPTION_FALSIFICATION", "FALS").replace("COMMUNICATION_PROBLEM", "COMM")
                 .replace("SENSOR_FAULT", "SENSOR").replace("GRID_EVENT", "GRID") for c in cols}
        L.append("| truth \\ predicted | " + " | ".join(short[c] for c in cols) + " |")
        L.append("|---|" + "---|" * len(cols))
        for r, row in cm.items():
            L.append(f"| {short.get(r, r)} | " + " | ".join(str(row[c]) for c in cols) + " |")
    L += ["", "## All blocks", "", "| Block | Events | Detection | Accuracy | Cases | Abstention | FP cases | FP/day |",
          "|---|---|---|---|---|---|---|---|"]
    for b, m in res["blocks"].items():
        L.append(f"| {b} | {m['n_events']} | {_fmt(m['event_detection_rate'], True)} | {_fmt(m['event_accuracy'], True)} | "
                 f"{m['n_cases']} | {_fmt(m['abstention_rate'], True)} | {m['false_positive_cases']} | {_fmt(m['false_positives_per_day'])} |")
    nb = res["normal_block"]
    L += ["", f"Normal-only block (in-sample, used to fit Stage A): {nb['cases']} cases ({nb['cases_per_day']} per day).", ""]
    L += ["## Event counts per label and block", "", "Requirement: >= 6 per label in test and >= 6 in train+val "
          "(normal motor starts occur naturally; the normal block holds no injected event).", "",
          "| Label | normal | train | val | test | train+val |", "|---|---|---|---|---|---|"]
    for lab, c in res["event_counts"].items():
        L.append(f"| {lab} | {c['normal']} | {c['train']} | {c['val']} | {c['test']} | {c['train'] + c['val']} |")
    lat = res.get("latency", {})
    if lat:
        L += ["", "## Latency (wall clock, this machine; varies between runs)", "", "| Measure | Value |", "|---|---|",
              f"| Stage A (detect) per 1-min decision cycle, amortised over the run | {lat.get('stage_a_per_minute_cycle_ms')} ms |",
              f"| Diagnosis + confidence + routing + explanation per case, p50 | {lat.get('decision_ms_p50')} ms |",
              f"| Diagnosis + confidence + routing + explanation per case, p95 | {lat.get('decision_ms_p95')} ms |"]
    cal = res.get("confidence_calibration")
    if cal:
        L += ["", "## Confidence calibration (validation block)", "",
              f"Method: {cal['method']} on {cal['n']} validation cases (shrunk toward the raw score with a 20-case prior). "
              f"Top-hypothesis accuracy on validation: {_fmt(cal.get('accuracy'), True)}; "
              f"ECE before: {_fmt(cal.get('ece_before'))}, after (in-sample): {_fmt(cal.get('ece_after'))}."]
    missed = et_test[~et_test.correct]
    if len(missed):
        L += ["", "## Test events not classified correctly", "", "| Event | Label | Equipment | Predicted | Detectability |",
              "|---|---|---|---|---|"]
        for _, r in missed.iterrows():
            L.append(f"| {r.event_id} | {r.label} | {r.equipment_id} | {r.predicted} | {r.detectability} |")
    L += ["", "## Known limitations", "",
          "- Synthetic data only; the detector was developed on the same simulator family, so these numbers are an "
          "upper bound for real data.",
          "- 1-min resolution: GRID_SAG is a sustained under-voltage (>= 1 min); inrush appears as a 1-min average.",
          "- Compound events (real overload during a meter CT drift) are scored like single events; the overload inside a drift "
          "episode is usually reported as part of the drift case.",
          "- AUX1 has a single meter; meter/energy hypotheses on AUX1 abstain by design (too few redundant paths).",
          ""]
    return "\n".join(L)
